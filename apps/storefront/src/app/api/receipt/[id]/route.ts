import { retrieveOrder } from "@lib/data/orders"
import { convertToLocale } from "@lib/util/money"

// Builds a printable HTML receipt for an order. Lives under /api so the
// country-code middleware leaves it alone.

const escape = (value: unknown) =>
  String(value ?? "").replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ]!
  )

export async function GET(
  _req: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params
  const order = await retrieveOrder(id).catch(() => null)

  if (!order) {
    return new Response("Receipt not available", { status: 404 })
  }

  const money = (amount?: number | null) =>
    convertToLocale({ amount: amount ?? 0, currency_code: order.currency_code })
  const address = order.shipping_address
  const rows = (order.items ?? [])
    .map(
      (item) =>
        `<tr><td>${escape(item.product_title)}<br><small>${escape(
          item.variant_title
        )}</small></td><td>${item.quantity}</td><td>${money(
          item.unit_price
        )}</td><td>${money(item.total)}</td></tr>`
    )
    .join("")

  const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>Receipt #${order.display_id} — Monsoon Coffee Co.</title>
<style>
  body { font-family: system-ui, sans-serif; color: #1a1c1c; max-width: 720px; margin: 40px auto; padding: 0 16px; }
  h1 { text-transform: uppercase; letter-spacing: .04em; margin-bottom: 0; }
  table { width: 100%; border-collapse: collapse; margin: 24px 0; }
  th, td { text-align: left; padding: 8px; border-bottom: 1px solid #ddd; vertical-align: top; }
  .totals td { border: 0; padding: 4px 8px; }
  .totals tr:last-child td { font-weight: 700; border-top: 2px solid #1a1c1c; }
  small { color: #666; }
</style></head>
<body>
  <h1>Monsoon Coffee Co.</h1>
  <p>Receipt for order <strong>#${order.display_id}</strong> · ${escape(
    new Date(order.created_at as string).toLocaleDateString("en-IN")
  )}</p>
  <p>${escape(address?.first_name)} ${escape(address?.last_name)}<br>
  ${escape(address?.address_1)}<br>${escape(address?.city)} ${escape(
    address?.postal_code
  )}<br>${escape(order.email)}</p>
  <table>
    <thead><tr><th>Item</th><th>Qty</th><th>Price</th><th>Total</th></tr></thead>
    <tbody>${rows}</tbody>
  </table>
  <table class="totals">
    <tr><td>Subtotal</td><td>${money(order.item_subtotal)}</td></tr>
    <tr><td>Discount</td><td>−${money(order.discount_total)}</td></tr>
    <tr><td>Shipping</td><td>${money(order.shipping_total)}</td></tr>
    <tr><td>Total</td><td>${money(order.total)}</td></tr>
  </table>
  <p><small>Demo receipt generated by the frontend-only storefront. No payment was taken.</small></p>
</body></html>`

  return new Response(html, {
    status: 200,
    headers: {
      "Content-Type": "text/html; charset=utf-8",
      "Content-Disposition": `attachment; filename="monsoon-receipt-${order.display_id}.html"`,
      "Cache-Control": "private, max-age=0, must-revalidate",
    },
  })
}
